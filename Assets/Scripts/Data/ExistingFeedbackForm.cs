    internal static bool Supports(FeedbackReport report)
    {
        if (report == null || report.submittedToExistingForm)
            return false;

        return report.kind == "session" ? report.sessionStats != null :
            report.kind == "level" && report.levelStats != null &&
            report.level != null && LevelFields.ContainsKey(report.level);
    }

    internal static WWWForm Build(FeedbackReport report)
    {
        var form = new WWWForm();
        if (report.kind == "session")
        {
            foreach (var field in SessionFields)
                Add(form, field.id, field.value(report.sessionStats));
            return form;
        }

        if (report.level == null || !LevelFields.TryGetValue(report.level, out string[] fields))
            return form;

        FeedbackLevelStats stats = report.levelStats;
        Add(form, fields[0], stats.timeUsed);
        Add(form, fields[1], stats.stepsTaken);
        if (report.outcome == nameof(FeedbackOutcome.Completed))
            Add(form, fields[2], stats.goalReachedTimer);
        else
            Add(form, fields[3], stats.quitTimer);

        Add(form, fields[4], stats.respawnTaken);
        Add(form, fields[5], stats.cameraRotationTaken);
        Add(form, fields[6], stats.freeCamTimer);
        Add(form, fields[7], stats.ability_Swim);
        Add(form, fields[8], stats.ability_SwiftSwim);
        Add(form, fields[9], stats.ability_Ascend);
        Add(form, fields[10], stats.ability_Descend);
        Add(form, fields[11], stats.ability_Dash);
        Add(form, fields[12], stats.ability_GrapplingHook);
        Add(form, fields[13], stats.ability_Jump);
        Add(form, fields[14], stats.ability_CeilingGrab);
        Add(form, fields[32], stats.talkTo_NPC);

        foreach (FeedbackPickup pickup in stats.pickups)
        {
            int field = pickup.item switch
            {
                "Essence" when pickup.index >= 1 && pickup.index <= 10 => 14 + pickup.index,
                "Footprint" when pickup.index >= 1 && pickup.index <= 3 => 24 + pickup.index,
                "Skin" when pickup.index == 1 => 28,
                "Ability" when pickup.index >= 1 && pickup.index <= 3 => 28 + pickup.index,
                _ => -1
            };
            if (field >= 0)
                Add(form, fields[field], pickup.seconds);
        }

        return form;
    }

    internal static bool ResponseWasRecorded(string body)
    {
        return !string.IsNullOrEmpty(body) &&
            (body.IndexOf("Your response has been recorded", StringComparison.OrdinalIgnoreCase) >= 0 ||
             body.IndexOf("Svaret ditt er registrert", StringComparison.OrdinalIgnoreCase) >= 0 ||
             body.IndexOf("responseConfirmationMessage", StringComparison.OrdinalIgnoreCase) >= 0 ||
             body.Contains("class=\"vHW8K\""));
    }

    private static void Add(WWWForm form, string field, double value)
    {
        if (!string.IsNullOrEmpty(field))
            form.AddField("entry." + field, Math.Max(0d, value).ToString("0.###", CultureInfo.InvariantCulture));
    }
